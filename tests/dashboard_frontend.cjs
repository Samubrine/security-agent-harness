// Run with: node --test tests/dashboard_frontend.cjs
const {test}=require('node:test');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');

test('recorded findings render, filter, and escape untrusted content',async()=>{
  const nodes=new Map();
  const node=key=>{
    if(!nodes.has(key)) nodes.set(key,{value:'',innerHTML:'',textContent:'',listeners:{},addEventListener(type,fn){this.listeners[type]=fn;},replaceChildren(){this.innerHTML='';},classList:{toggle(){}},showModal(){this.open=true;},close(){this.open=false;}});
    return nodes.get(key);
  };
  const record={run:{status:'completed',skill:'port_scan',model:{}},findings:[{id:'f1',title:'<script>alert(1)</script>',severity:'critical',status:'possible',claims:[]}],events:[{seq:1,type:'RUN_STARTED',at:'2026-10-19T12:00:00Z',data:{}},{seq:2,type:'RUN_ENDED',at:'2026-10-19T12:00:01Z',data:{reason:'<unsafe>'}}],observations:[],gaps:[],report:'Report'};
  const timers=new Map();let timerId=0;
  const saved=new Map();
  const systemTheme={matches:false,addEventListener(type,fn){this.listener=fn;}};
  const documentRoot={dataset:{}};
  const context=vm.createContext({window:{matchMedia:()=>systemTheme},localStorage:{getItem:key=>saved.get(key),setItem:(key,value)=>saved.set(key,value)},document:{documentElement:documentRoot,querySelector:node,querySelectorAll:()=>[],addEventListener(){}},fetch:async url=>({ok:true,json:async()=>url==='/api/runs'?[{directory:'demo',skill:'port_scan'}]:record}),Date,Blob,URL,setTimeout:(fn)=>{timers.set(++timerId,fn);return timerId;},clearTimeout:id=>timers.delete(id)});
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/harness/web/app.js'),'utf8'),context);
  await new Promise(resolve=>setImmediate(resolve));
  assert.match(node('#content').innerHTML,/Total findings/);
  assert.match(node('#content').innerHTML,/&lt;script&gt;/);
  assert.doesNotMatch(node('#content').innerHTML,/<script>/);
  assert.match(node('#content').innerHTML,/Confirmed \/ possible/);
  assert.match(node('#content').innerHTML,/<meter/);
  assert.match(node('#content').innerHTML,/Not recorded/);
  assert.equal(documentRoot.dataset.theme,'light');
  node('#theme').value='dark';node('#theme').listeners.change();
  assert.equal(documentRoot.dataset.theme,'dark');
  assert.equal(saved.get('aegis-theme'),'dark');
  node('#theme').value='system';node('#theme').listeners.change();
  systemTheme.matches=true;systemTheme.listener();
  assert.equal(documentRoot.dataset.theme,'dark');
  vm.runInContext("view='trace';render()",context);
  assert.match(node('#trace-events').innerHTML,/RUN ENDED/);
  assert.match(node('#trace-events').innerHTML,/&lt;unsafe&gt;/);
  node('#trace-reset').listeners.click();
  assert.match(node('#trace-count').textContent,/0 \/ 2/);
  node('#trace-next').listeners.click();
  assert.match(node('#trace-count').textContent,/1 \/ 2/);
  node('#trace-play').listeners.click();
  assert.equal(timers.size,1);
  const [id,tick]=[...timers.entries()][0];timers.delete(id);tick();
  assert.match(node('#trace-count').textContent,/End of recording/);
  assert.equal(node('#trace-next').disabled,true);
  node('#trace-play').listeners.click();
  node('#trace-play').listeners.click();
  assert.equal(timers.size,0);
  node('#trace-progress').value='1';node('#trace-progress').listeners.input();
  assert.match(node('#trace-count').textContent,/1 \/ 2/);
  vm.runInContext("view='findings';render()",context);
  assert.match(node('#finding-results').innerHTML,/f1/);
  node('#search').value='no-match';node('#search').listeners.input();
  assert.match(node('#finding-results').innerHTML,/No findings match/);
  node('#search').value='';node('#severity').value='low';node('#severity').listeners.change();
  assert.match(node('#finding-results').innerHTML,/No findings match/);
  vm.runInContext("view='report';render()",context);
  assert.match(node('#content').innerHTML,/Download .md/);
  record.report='# Investigation\n\n**Status:** completed\n\n| Severity | Count |\n|---|---|\n| High | 2 |\n\n1. Finding\n   - Evidence `id_1`\n\n<script>alert(1)</script>\n\n[unsafe](javascript:alert)\n\n[reference](https://example.com)\n\n```\n<img src=x onerror=alert(1)>\n```';
  vm.runInContext("render()",context);
  const report=node('#content').innerHTML;
  assert.match(report,/<h1>Investigation<\/h1>/);
  assert.match(report,/<strong>Status:<\/strong>/);
  assert.match(report,/<table>/);
  assert.match(report,/<th scope="col">Severity<\/th>/);
  assert.match(report,/<ol start="1"><li>Finding<ul><li>Evidence <code>id_1<\/code>/);
  assert.match(report,/&lt;script&gt;/);
  assert.doesNotMatch(report,/<script>|<img|href="javascript:/);
  assert.match(report,/href="https:\/\/example.com"/);
  assert.match(report,/<pre><code>&lt;img/);
  // Also exercise the real bundled report, including its finding lists/tables.
  const reportPath=path.join(__dirname,'../runs/quickstart/report.md');
  if(fs.existsSync(reportPath)) {
    record.report=fs.readFileSync(reportPath,'utf8');vm.runInContext('render()',context);
    assert.match(node('#content').innerHTML,/<h2>Findings<\/h2>/);
    assert.match(node('#content').innerHTML,/<table>/);
  }
  const index=fs.readFileSync(path.join(__dirname,'../src/harness/web/index.html'),'utf8');
  assert.doesNotMatch(index,/class="logo"/);
});
